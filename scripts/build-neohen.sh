#!/usr/bin/env bash
# Build NeoHEN: OnionHEN's pipeline with NeoHEN branding and kstuff kept
# outside the payload (loaded from /data/neohen/kstuff.elf on the console).
# Any extra arguments go to scripts/build.sh, e.g. --release --jobs 8.
set -euo pipefail
export ONION_BRAND_NAME="${ONION_BRAND_NAME:-NeoHEN}"
export ONION_DIR_NAME="${ONION_DIR_NAME:-neohen}"
export ONION_DIR_NAME_LOWER="${ONION_DIR_NAME_LOWER:-neohen}"
export ONION_ISSUES_URL="${ONION_ISSUES_URL:-https://github.com/neox69/NeoHEN/issues}"
export ONION_PAYLOAD_NAME="${ONION_PAYLOAD_NAME:-NeoHEN}"
export ONION_EMBED_KSTUFF="${ONION_EMBED_KSTUFF:-OFF}"
export ONION_HIDE_UNTESTED="${ONION_HIDE_UNTESTED:-ON}"
export ONION_PRODUCT_VERSION="${ONION_PRODUCT_VERSION:-0.1.0-rc1}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Generated by tools/branding/make_icons.py from branding/. Until it exists
# the build keeps OnionHEN's icon and says so.
# NEOHEN_ICON=light (default, ~6 KB) or full (~23 KB, all colours).
case "${NEOHEN_ICON:-light}" in
  full) NEOHEN_ICON="${ROOT}/source/bootstrapper/assets/neohen/neohen_sicon_full.png" ;;
  light) NEOHEN_ICON="${ROOT}/source/bootstrapper/assets/neohen/neohen_sicon.png" ;;
  *) echo "[error] NEOHEN_ICON must be light or full" >&2; exit 2 ;;
esac
if [[ -z "${ONION_STARTUP_ICON:-}" ]]; then
  if [[ -f "${NEOHEN_ICON}" ]]; then
    export ONION_STARTUP_ICON="${NEOHEN_ICON}"
  else
    echo "[warn] ${NEOHEN_ICON} missing: building with the OnionHEN icon" >&2
  fi
fi
exec "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/build.sh" "$@"
